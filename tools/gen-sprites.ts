// Generates src/sprites_data.rs from clawd-buddy's hooks/sprites.ts.
//
// Usage:
//   bun tools/gen-sprites.ts                 reads the file from clawd-buddy's lottie-acts branch via git show
//   bun tools/gen-sprites.ts --from <path>   reads a checked-out sprites.ts instead
//   bun tools/gen-sprites.ts --repo <path> --ref <branch>   overrides the git show source
//
// The input is read as text and its SHEETS and ACTS object literals are parsed
// as JSON; the TypeScript is never executed.

const args = process.argv.slice(2)
const flag = (name: string) => {
  const i = args.indexOf(name)
  return i >= 0 ? args[i + 1] : undefined
}

const from = flag("--from")
const repo = flag("--repo") ?? "D:/Python/clawd-buddy"
const ref = flag("--ref") ?? "lottie-acts"
const out = flag("--out") ?? `${import.meta.dir}/../src/sprites_data.rs`

async function readSource(): Promise<string> {
  if (from) return await Bun.file(from).text()
  const p = Bun.spawnSync(["git", "-C", repo, "show", `${ref}:plugins/clawd-buddy/hooks/sprites.ts`])
  if (p.exitCode !== 0) throw new Error(`git show failed: ${p.stderr.toString()}`)
  return p.stdout.toString()
}

// Finds `export const NAME ... = { ... }` and returns the balanced object
// literal after the `=`. String contents are skipped so braces in them do not count.
function objectLiteral(src: string, name: string): any {
  const m = new RegExp(`export const ${name}\\b[^=]*=\\s*`).exec(src)
  if (!m) throw new Error(`no export const ${name}`)
  let i = m.index + m[0].length
  if (src[i] !== "{") throw new Error(`${name} is not an object literal`)
  const start = i
  let depth = 0
  let inStr = false
  for (; i < src.length; i++) {
    const c = src[i]
    if (inStr) {
      if (c === "\\") i++
      else if (c === '"') inStr = false
      continue
    }
    if (c === '"') inStr = true
    else if (c === "{" || c === "[") depth++
    else if (c === "}" || c === "]") {
      depth--
      if (depth === 0) return JSON.parse(src.slice(start, i + 1))
    }
  }
  throw new Error(`unterminated ${name}`)
}

const CLEAR = 46 // b'.', never a palette index

// Expands base + deltas into full frames of palette indices.
function expand(name: string, v: any): number[][] {
  const n = v.w * v.h
  if (v.base.length !== n) throw new Error(`${name}: base is ${v.base.length}, want ${n}`)
  const decode = (c: string) => (c === "." ? CLEAR : parseInt(c, 36))
  let cur = Array.from(v.base as string, decode)
  const frames = [cur]
  for (const d of v.deltas as string[]) {
    cur = cur.slice()
    if (d) {
      for (const op of d.split(",")) {
        const idx = parseInt(op.slice(0, -1), 36)
        if (!(idx >= 0 && idx < n)) throw new Error(`${name}: bad op ${op}`)
        cur[idx] = decode(op.slice(-1))
      }
    }
    frames.push(cur)
  }
  for (const f of frames) for (const p of f) if (p !== CLEAR && p >= v.palette.length) throw new Error(`${name}: index ${p} past palette`)
  return frames
}

const src = await readSource()
const SHEETS = objectLiteral(src, "SHEETS")
const ACTS = objectLiteral(src, "ACTS")

const pool = new Map<string, number>()
const poolLines: string[] = []

function esc(b: number): string {
  if (b === CLEAR) return "."
  if (b === 0) return "\\0"
  return "\\x" + b.toString(16).padStart(2, "0")
}

function frameRef(w: number, f: number[]): string {
  const key = w + ":" + f.join(",")
  let id = pool.get(key)
  if (id === undefined) {
    id = pool.size
    pool.set(key, id)
    const rows: string[] = []
    for (let y = 0; y < f.length / w; y++) rows.push(f.slice(y * w, y * w + w).map(esc).join(""))
    poolLines.push(`static F${id}: [u8; ${f.length}] = *b"\\\n    ${rows.join("\\\n    ")}";`)
  }
  return `&F${id}`
}

const palette = (p: string[]) => `&[${p.map((c) => "0x" + c.slice(1).toLowerCase()).join(", ")}]`
const frameList = (w: number, fs: number[][]) => `&[${fs.map((f) => frameRef(w, f)).join(", ")}]`
const num = (x: number) => (Number.isInteger(x) ? x.toFixed(1) : String(x))

const sheetLines: string[] = []
for (const [name, v] of Object.entries<any>(SHEETS)) {
  const fs = expand(name, v)
  sheetLines.push(
    `    Sheet { name: "${name}", w: ${v.w}, h: ${v.h}, palette: ${palette(v.palette)}, frames: ${frameList(v.w, fs)}, ` +
      `launch: ${v.launch}, cruise: &[${v.cruise.join(", ")}], outro: ${v.outro}, speed: ${num(v.speed)} },`,
  )
}
const actLines: string[] = []
for (const [name, v] of Object.entries<any>(ACTS)) {
  const fs = expand(name, v)
  if (fs.length !== v.frames) throw new Error(`${name}: ${fs.length} frames, header says ${v.frames}`)
  actLines.push(
    `    Act { name: "${name}", w: ${v.w}, h: ${v.h}, palette: ${palette(v.palette)}, frames: ${frameList(v.w, fs)}, ` +
      `weight: ${num(v.weight)}, x: ${v.x}, y: ${v.y} },`,
  )
}

const rs = `// Generated by tools/gen-sprites.ts from clawd-buddy's hooks/sprites.ts.
// Do not edit by hand. The art is Anthropic's, from https://claude.dev (see NOTICE).
//
// Each frame is w * h palette indices, row-major, top row first. CLEAR marks a
// transparent pixel. Palettes are 0xRRGGBB.

use crate::sprites::{Act, Sheet};

pub const CLEAR: u8 = ${CLEAR};

pub static SHEETS: [Sheet; ${sheetLines.length}] = [
${sheetLines.join("\n")}
];

pub static ACTS: [Act; ${actLines.length}] = [
${actLines.join("\n")}
];

${poolLines.join("\n")}
`

await Bun.write(out, rs)
console.log(`wrote ${out}: ${sheetLines.length} sheets, ${actLines.length} acts, ${pool.size} unique frames, ${rs.length} bytes`)
